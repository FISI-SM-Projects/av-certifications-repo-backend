CREATE DATABASE av_certifications_db;

\c av_certifications_db;

CREATE SCHEMA IF NOT EXISTS public;

-- ENUMS
CREATE TYPE "department" AS ENUM (
	'CC',
	'SW',
	'EG',
	'NA'
);

CREATE TYPE "school" AS ENUM (
	'SW',
	'CC',
	'SI',
	'IA'
);

CREATE TYPE "account_status" AS ENUM (
	'ACTIVO',
	'SUSPENDIDO',
	'ELIMINADO'
);

CREATE TYPE "role" AS ENUM (
	'DOCENTE',
	'DIRECTOR_ESCUELA',
	'DEPARTAMENTO',
	'DECANATO',
	'ADMIN',
	'ALUMNO'
);

CREATE TYPE "certification_status" AS ENUM (
	'EMITIDO',
	'VERIFICADO',
	'EN_REVISION',
	'NO_EMITIDO',
	'REVOCADO'
);

-- TABLES
CREATE TABLE IF NOT EXISTS "person" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"first_name" VARCHAR(120) NOT NULL,
	"paternal_last_name" VARCHAR(80) NOT NULL,
	"maternal_last_name" VARCHAR(80) NOT NULL,
	"dni" VARCHAR(8) UNIQUE,
	"register_state" ACCOUNT_STATUS DEFAULT 'ACTIVO',
	"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	"updated_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "institutional_account" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"person_id" BIGINT NOT NULL,
	"ldap_uid" VARCHAR(100) NOT NULL UNIQUE,
	"institutional_email" VARCHAR(180) NOT NULL UNIQUE,
	"main" BOOLEAN DEFAULT FALSE,
	"account_status" ACCOUNT_STATUS DEFAULT 'ACTIVO',
	"updated_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "system_permission" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"code" VARCHAR(10) NOT NULL UNIQUE,
	"name" VARCHAR(80) NOT NULL,
	"description" VARCHAR(100) DEFAULT 'No disponible',
	"active" BOOLEAN DEFAULT TRUE,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "system_role" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"code" ROLE NOT NULL UNIQUE,
	"name" VARCHAR(80) NOT NULL,
	"description" VARCHAR(100) DEFAULT 'No disponible',
	"active" BOOLEAN DEFAULT TRUE,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "role_permission" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"system_role_id" BIGINT NOT NULL,
	"system_permission_id" BIGINT NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "account_system_role" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"account_id" BIGINT NOT NULL,
	"system_role_id" BIGINT NOT NULL,
	"granted_by_account_id" BIGINT NOT NULL,
	"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	"active" BOOLEAN DEFAULT TRUE,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "teacher" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"person_id" BIGINT NOT NULL,
	"code" INT NOT NULL UNIQUE,
	"moodle_id" INT NOT NULL UNIQUE,
	"department" DEPARTMENT DEFAULT 'NA',
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "academic_period" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"semester_code" VARCHAR(10) NOT NULL UNIQUE,
	"name" VARCHAR(80) NOT NULL,
	"description" VARCHAR(250) DEFAULT 'No disponible',
	"start_date" DATE NOT NULL,
	"end_date" DATE NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "course" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"code" VARCHAR(10) NOT NULL UNIQUE,
	"name" VARCHAR(80) NOT NULL,
	"description" VARCHAR(250) DEFAULT 'No disponible',
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "academic_workload" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"course_id" BIGINT NOT NULL,
	"academic_period_id" BIGINT NOT NULL,
	"teacher_id" BIGINT NOT NULL,
	"moodle_id" INT NOT NULL UNIQUE,
	"cycle" INT NOT NULL,
	"section" INT NOT NULL,
	"school" SCHOOL NOT NULL,
	"plan" INT NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "certification" (
	"id" BIGINT NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"academic_workload_id" BIGINT NOT NULL,
	"document_path" VARCHAR(500) NOT NULL,
	"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	"updated_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	"status" CERTIFICATION_STATUS DEFAULT 'EMITIDO',
	PRIMARY KEY("id")
);

